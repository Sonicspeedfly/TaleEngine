def jailbreak_block(cfg: Optional[dict]) -> str:
    """
    Глобальные инструкции пользователя, добавляемые в САМЫЙ конец контекста
    (сильнейшая позиция — прямо перед ответом), поверх Post-History персонажа.

    Текст пишет пользователь: приложение даёт место инъекции и библиотеку
    пресетов, но собственных обходных промптов не содержит.

    :param cfg: {"enabled": bool, "text": str} из настроек интерфейса.
    """
    if not cfg or not cfg.get("enabled"):
        return ""
    return (cfg.get("text") or "").strip()


async def load_global_instructions(db) -> str:
    """
    Глобальные инструкции из настроек интерфейса (ключ 'ui' -> 'jailbreak').

    Читается ВНУТРИ сборки контекста, а не в каждом эндпоинте: иначе новую точку
    вызова легко забыть, и в каком-то режиме (группа, Telegram, регенерация)
    инструкции молча не применятся.
    """
    try:
        from backend import models

        row = await db.get(models.AppSetting, "ui")
        value = row.value if row and isinstance(row.value, dict) else {}
        return jailbreak_block(value.get("jailbreak"))
    except Exception:  # noqa: BLE001 — настройка не должна ронять ход
        return ""
