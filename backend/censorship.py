"""
Обход цензуры провайдера: пороги фильтров, диагностика блокировок, свои инструкции.

Что важно понимать (и что раньше приложение не объясняло пользователю):

1. У Gemini ДВА РАЗНЫХ вида фильтров.
   * НАСТРАИВАЕМЫЕ — пять категорий HARM_CATEGORY_* (домогательства, ненависть,
     откровенный контент, опасный контент, гражданская добропорядочность). Ими
     управляет `safety_settings`, и порог "OFF" снимает их полностью.
   * НЕОТКЛЮЧАЕМЫЕ — PROHIBITED_CONTENT, SPII, BLOCKLIST, RECITATION, IMAGE_*.
     Они срабатывают ВСЕГДА, независимо от safety_settings. Никакая настройка
     в интерфейсе их не выключит — это ограничение на стороне Google.

   Раньше на любую пустоту приложение писало «попробуйте переформулировать» —
   и пользователь крутил ползунки, которые к его случаю отношения не имели.
   Теперь по finish_reason видно, ЧТО именно сработало и можно ли с этим что-то
   сделать в настройках.

2. Режим размышлений (thinking) добавляет СОБСТВЕННУЮ модерацию поверх
   safety_settings. Отсюда эффект «снял фильтры, а всё равно душит»: виноват не
   порог, а включённые рассуждения. См. reasoning_conflict().

Собственный текст «джейлбрейка» пишет ПОЛЬЗОВАТЕЛЬ: приложение даёт поле,
библиотеку пресетов и место инъекции, но готовых обходных промптов не содержит.
"""
from typing import Optional

# Настраиваемые категории Gemini. Порядок — как в консоли Google, для UI.
SAFETY_CATEGORIES = [
    ("HARM_CATEGORY_HARASSMENT", "Домогательства и травля"),
    ("HARM_CATEGORY_HATE_SPEECH", "Ненависть и вражда"),
    ("HARM_CATEGORY_SEXUALLY_EXPLICIT", "Откровенный контент"),
    ("HARM_CATEGORY_DANGEROUS_CONTENT", "Опасный контент"),
    ("HARM_CATEGORY_CIVIC_INTEGRITY", "Гражданская добропорядочность"),
]

# Пороги от самого свободного к самому строгому.
#   OFF             — фильтр ВЫКЛЮЧЕН полностью (у Gemini 2.5/3 это и так дефолт);
#   BLOCK_NONE      — не блокировать, но оценивать (мягче, чем OFF);
#   BLOCK_ONLY_HIGH — блокировать только явные нарушения;
#   ""              — не передавать порог, решает провайдер.
THRESHOLDS = ["OFF", "BLOCK_NONE", "BLOCK_ONLY_HIGH", ""]

# Готовые наборы для интерфейса: id -> порог для ВСЕХ категорий.
PRESETS = {
    "off": "OFF",
    "none": "BLOCK_NONE",
    "high_only": "BLOCK_ONLY_HIGH",
    "provider": "",
}


def safety_settings(preset: str = "off", overrides: Optional[dict] = None) -> list[dict]:
    """
    Список safety_settings для Gemini/Vertex.

    :param preset: ключ из PRESETS — базовый порог для всех категорий.
    :param overrides: точечные пороги {категория: порог}, важнее пресета.
        Пустой порог ("") означает «не передавать эту категорию вовсе».
    :return: [] если передавать нечего (тогда решает провайдер).
    """
    base = PRESETS.get((preset or "off").lower(), "OFF")
    overrides = overrides or {}
    out: list[dict] = []
    for cat, _ in SAFETY_CATEGORIES:
        threshold = overrides.get(cat, base)
        if threshold in THRESHOLDS and threshold:
            out.append({"category": cat, "threshold": threshold})
    return out


# ---------------------------------------------------------------------------
# Диагностика: почему ответ пустой
# ---------------------------------------------------------------------------
# Блокировки, которые СНИМАЮТСЯ порогами safety_settings.
_CONFIGURABLE = {"SAFETY", "CONTENT_FILTER", "CONTENT_POLICY_VIOLATION"}

# Блокировки Google, которые safety_settings НЕ отключает ни при каких порогах.
_NON_CONFIGURABLE = {
    "PROHIBITED_CONTENT": (
        "запрещённый контент — это НЕотключаемый фильтр Google, он не зависит от "
        "порогов безопасности и не снимается никакими настройками"
    ),
    "SPII": (
        "модель решила, что в тексте персональные данные (SPII). Фильтр "
        "неотключаемый; помогает убрать из текста похожее на реальные документы, "
        "номера, адреса"
    ),
    "BLOCKLIST": (
        "сработал терминологический стоп-лист провайдера. Фильтр неотключаемый; "
        "помогает заменить конкретные слова-триггеры"
    ),
    "RECITATION": (
        "ответ слишком близко повторял защищённый авторским правом источник. "
        "Фильтр неотключаемый; помогает попросить пересказ своими словами"
    ),
    "IMAGE_SAFETY": "изображение не прошло фильтр безопасности (неотключаемый)",
    "IMAGE_PROHIBITED_CONTENT": "запрещённое содержимое изображения (неотключаемый)",
}


def reasoning_conflict(reasoning: str, safety_off: bool) -> bool:
    """
    Конфликт «рассуждения + снятые фильтры»: у Gemini режим размышлений включает
    СВОЮ модерацию во время reasoning, и она душит контент даже при порогах OFF.

    Автоматически мы thinking в этом режиме не включаем (см. llm_gateway), но
    пользователь может выбрать уровень вручную — и тогда обход тихо перестаёт
    работать. Об этом надо предупреждать явно, а не оставлять гадать.
    """
    return bool(safety_off) and (reasoning or "").lower() not in ("", "auto", "disable")


def explain_block(
    finish_reason: Optional[str],
    *,
    thought_len: int = 0,
    safety_off: bool = True,
    reasoning: str = "",
    max_tokens: Optional[int] = None,
) -> str:
    """
    Человеческое объяснение, почему модель вернула ПУСТОЙ ответ, и что делать.

    Раньше на все случаи выдавался один общий текст, и пользователь крутил
    настройки, которые к его блокировке отношения не имели.
    """
    fr = (finish_reason or "").strip().upper()
    lines: list[str] = []

    if fr in _NON_CONFIGURABLE:
        lines.append(f"⛔ Провайдер заблокировал ответ: {_NON_CONFIGURABLE[fr]}.")
        lines.append(
            "Zero-Censorship и пороги безопасности здесь НЕ помогут — это фильтр "
            "Google поверх настраиваемых. Реально помогает: переформулировать "
            "запрос, сменить модель или зайти в сцену с другой стороны."
        )
    elif fr in _CONFIGURABLE:
        lines.append("⛔ Сработал НАСТРАИВАЕМЫЙ фильтр безопасности провайдера.")
        if safety_off:
            lines.append(
                "Фильтры уже сняты (порог OFF), значит блокировка пришла с другой "
                "стороны — чаще всего это модерация внутри режима размышлений или "
                "фильтр самого прокси."
            )
        else:
            lines.append(
                "Включите Zero-Censorship (⚙ → Генерация → «🛡 Обход цензуры») — "
                "он ставит порог OFF на все настраиваемые категории."
            )
    elif fr in ("LENGTH", "MAX_TOKENS"):
        lines.append("⛔ Лимит длины ответа исчерпан ДО того, как модель начала писать.")
        if thought_len:
            lines.append(
                f"Размышления съели весь лимит ({thought_len} симв. мыслей). "
                "Поднимите Max tokens или снизьте бюджет размышлений."
            )
    else:
        lines.append(
            f"⛔ Модель вернула пустой ответ (finish_reason={finish_reason or 'не указан'})."
        )
        lines.append(
            "Обычно это фильтр контента провайдера или исчерпание лимита ответа "
            "на размышления."
        )

    # Ловушка, которую пользователь сам не увидит: рассуждения возвращают цензуру.
    if reasoning_conflict(reasoning, safety_off):
        lines.append(
            f"⚠ У вас включены размышления («{reasoning}») ВМЕСТЕ со снятыми фильтрами. "
            "У Gemini режим размышлений добавляет собственную модерацию поверх "
            "safety_settings — она душит контент даже при пороге OFF. Попробуйте "
            "поставить размышления в «выключены»."
        )
    if thought_len and fr not in ("LENGTH", "MAX_TOKENS"):
        lines.append(f"(модель успела «подумать» {thought_len} симв., но ответ не выдала)")
    if max_tokens and max_tokens < 2048 and thought_len:
        lines.append(
            f"(Max tokens = {max_tokens} — маловато, когда размышления тратят тот же лимит)"
        )
    # Техническая строка — всегда: по ней ищут причину в документации провайдера
    # и в наших логах. Человеческое объяснение её не заменяет, а дополняет.
    lines.append(
        f"Технически: ПУСТОЙ ответ, finish_reason={finish_reason or 'не указан'}."
    )
    return "\n".join(lines)


